def glyph(ch: str) -> bytes:
    """字の形の5列(1バイトが縦の1列、ビット0が上)。描いていない字は空白"""
    rows = FONT.get(ch)
    if rows is None:
        return bytes(5)
    return bytes(sum(1 << y for y in range(7) if rows[y][x] == "#") for x in range(5))


def font_addr(code: int) -> int:
    """本体の文字コードcodeの形の番地(PC-1251のROMと同じ)"""
    return (0x4414 if code < 0x20 else 0x43C4) + 5 * code


def install(m) -> None:
    """文字の形の表を、ROMの番地に書く(ROMなしの本体だけ)"""
    if not m.norom:
        return
    for code, ch in CHARS.items():
        if 0x11 <= code < 0x20 or 0x30 <= code < 0x6B:
            at = font_addr(code)
            m.mem[at : at + 5] = glyph(ch)


# キーの名前(machine.KEYS)から、ROMのキーを読むルーチンが返す本体の文字コードへ。
# 英字・数字・記号は文字コードの表から引く。ほかは確かめたものだけ
KEY_CODES = {ch: code for code, ch in CHARS.items() if len(ch) == 1}
KEY_CODES.update({"ENTER": 0x00, "CL": 0x02, "LEFT": 0x0F, "SPC": 0x11})


def _keyscan(m) -> None:
    """1F44: キーを1回読む。押されていればCを1、Aに本体の文字コード。なければCを0"""
    cpu = m.cpu
    codes = sorted(KEY_CODES[k] for k in m.held if k in KEY_CODES)
    if codes:
        cpu.ram[2] = codes[0]
        cpu.c = 1
    else:
        cpu.c = 0


def _glyph_addr(m) -> None:
    """1FBC: Aの文字コードの形の番地−1をXに入れる"""
    cpu = m.cpu
    x = (font_addr(cpu.ram[2]) - 1) & 0xFFFF
    cpu.ram[4], cpu.ram[5] = x & 0xFF, x >> 8


# 番地: (働き, 代わりに動かす関数, 使ったことにするサイクル数)
ROUTINES = {
    0x1F44: ("キーを1回読む", _keyscan, 120),
    0x1FBC: ("文字の形の番地を求める", _glyph_addr, 60),
}


def call(m, addr: int) -> bool:
    """addrがまねられるROMのルーチンの入口なら、働きをまねて呼んだ所へ戻し、Trueを返す"""
    if not m.norom or addr not in ROUTINES:
        return False
    _name, fn, cycles = ROUTINES[addr]
    fn(m)
    cpu = m.cpu
    lo = cpu.pop()
    cpu.pc = lo | cpu.pop() << 8  # RTNと同じ
    m.pass_time(cycles)
    return True
